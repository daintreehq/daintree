export type SessionAgentId = "codex" | "claude";

/**
 * - `prompt`: something the user typed, a slash command as the command itself.
 * - `context`: text the CLI or Daintree injected (environment blocks,
 *   AGENTS.md, reminders, notices, compaction summaries). Searchable, never
 *   quoted in a hand-off as the user's request or the agent's reply.
 * - `assistant`: the agent's reply text.
 * - `tool_call` / `tool_result`: a tool's input and its output.
 */
export type FragmentKind = "prompt" | "context" | "assistant" | "tool_call" | "tool_result";

export interface RecordFragment {
  readonly kind: FragmentKind;
  readonly text: string;
  /** Groups the blocks of one reply that the CLI split across records. */
  readonly messageKey?: string;
}

export interface ParsedRecord {
  /** The session id the record names, when it names one. */
  readonly sessionId: string | null;
  /** True for a record that belongs to a subagent, never to the session itself. */
  readonly sidechain: boolean;
  readonly timestamp: string | null;
  readonly fragments: readonly RecordFragment[];
}

const EMPTY: ParsedRecord = { sessionId: null, sidechain: false, timestamp: null, fragments: [] };

/**
 * Tool input is code or arguments, and tool output can be megabytes of logs.
 * Both are indexed up to here, enough to find a command or an error by its
 * words, without a huge build log outweighing the conversation.
 */
export const TOOL_TEXT_MAX_CHARS = 16_000;

/** User-role text the CLIs inject ahead of or between real prompts. */
const INJECTED_PREFIXES = [
  "<environment_context>",
  "<user_instructions>",
  "<INSTRUCTIONS>",
  "<turn_aborted>",
  "# AGENTS.md instructions",
  "<command-message>",
  "<command-name>",
  "<command-args>",
  "<local-command-",
  "<task-notification>",
  "<system-reminder>",
  "Caveat: The messages below were generated by the user",
  // Notices Daintree types into an agent's input (electron/services/mcp-server/noticeFormat.ts).
  "Daintree: ",
];

export function parseRecord(agentId: SessionAgentId, text: string): ParsedRecord | null {
  let parsed: unknown;
  try {
    parsed = JSON.parse(text);
  } catch {
    return null;
  }
  const record = asObject(parsed);
  if (!record) return null;
  return agentId === "codex" ? parseCodexRecord(record) : parseClaudeRecord(record);
}

/**
 * A rollout's `response_item` records are what the model saw and said, and
 * keep their shape across codex-cli versions; the `event_msg` copies of the
 * same turns changed shape between versions, so they are not read.
 * Reasoning is encrypted or private and is skipped.
 */
function parseCodexRecord(record: Record<string, unknown>): ParsedRecord {
  const timestamp = typeof record.timestamp === "string" ? record.timestamp : null;
  const payload = asObject(record.payload);
  if (!payload) return { ...EMPTY, timestamp };
  if (record.type === "session_meta") {
    return { ...EMPTY, timestamp, sessionId: stringOrNull(payload.id) };
  }
  if (record.type !== "response_item") return { ...EMPTY, timestamp };

  const fragments: RecordFragment[] = [];
  switch (payload.type) {
    case "message": {
      const body = joinText(payload.content, ["input_text", "output_text", "text"]);
      if (!body) break;
      if (payload.role === "user") {
        fragments.push({ kind: isInjected(body) ? "context" : "prompt", text: body });
      } else if (payload.role === "assistant") {
        fragments.push({ kind: "assistant", text: body });
      }
      break;
    }
    case "function_call":
    case "custom_tool_call": {
      const name = stringOrNull(payload.name) ?? "tool";
      const input = stringOrNull(payload.arguments) ?? stringOrNull(payload.input) ?? "";
      fragments.push({ kind: "tool_call", text: capTool(`${name} ${input}`) });
      break;
    }
    case "local_shell_call": {
      const action = asObject(payload.action);
      const command = Array.isArray(action?.command)
        ? action.command.filter((part) => typeof part === "string").join(" ")
        : "";
      if (command) fragments.push({ kind: "tool_call", text: capTool(`shell ${command}`) });
      break;
    }
    case "web_search_call": {
      // `search` carries `query` or `queries`, `open_page` a `url`, and
      // `find_in_page` a `url` and a `pattern`.
      const action = asObject(payload.action);
      const queries = Array.isArray(action?.queries) ? action.queries : [];
      const parts = [action?.query, ...queries, action?.url, action?.pattern].filter(
        (part): part is string => typeof part === "string" && part.length > 0
      );
      if (parts.length > 0) {
        const kind = stringOrNull(action?.type) ?? "search";
        fragments.push({ kind: "tool_call", text: capTool(`web_${kind} ${parts.join(" ")}`) });
      }
      break;
    }
    case "function_call_output":
    case "custom_tool_call_output":
    case "local_shell_call_output": {
      const output = toolOutputText(payload.output);
      if (output) fragments.push({ kind: "tool_result", text: capTool(output) });
      break;
    }
    default:
      break;
  }
  return { sessionId: null, sidechain: false, timestamp, fragments };
}

function parseClaudeRecord(record: Record<string, unknown>): ParsedRecord {
  const timestamp = typeof record.timestamp === "string" ? record.timestamp : null;
  const sessionId = stringOrNull(record.sessionId);
  const sidechain = record.isSidechain === true;
  const empty: ParsedRecord = { sessionId, sidechain, timestamp, fragments: [] };
  if (record.type !== "user" && record.type !== "assistant") return empty;
  const message = asObject(record.message);
  if (!message || sidechain) return empty;

  // A compaction summary or a meta record is the CLI's own text, never the
  // user's request or the agent's reply, whatever it quotes.
  const meta = record.isMeta === true || record.isCompactSummary === true;
  const content = message.content;
  const blocks: unknown[] = typeof content === "string" ? [{ type: "text", text: content }] : [];
  if (Array.isArray(content)) blocks.push(...content);

  const texts: string[] = [];
  const tools: RecordFragment[] = [];
  for (const raw of blocks) {
    const block = asObject(raw);
    if (!block) continue;
    if (block.type === "text") {
      const body = typeof block.text === "string" ? block.text.trim() : "";
      if (body) texts.push(body);
    } else if (block.type === "tool_use") {
      const name = stringOrNull(block.name) ?? "tool";
      tools.push({ kind: "tool_call", text: capTool(`${name} ${safeJson(block.input)}`) });
    } else if (block.type === "tool_result") {
      const output = toolOutputText(block.content);
      if (output) tools.push({ kind: "tool_result", text: capTool(output) });
    }
    // `thinking`, `redacted_thinking` and `image` blocks are not indexed.
  }

  const fragments: RecordFragment[] = [];
  if (record.type === "assistant") {
    // Every text block of one reply, as one fragment, keyed by the API message
    // so the blocks a long reply was split across records into stay together.
    const body = texts.join("\n\n");
    if (body) {
      fragments.push(
        meta
          ? { kind: "context", text: body }
          : { kind: "assistant", text: body, messageKey: stringOrNull(message.id) ?? undefined }
      );
    }
  } else {
    fragments.push(...userFragments(texts, meta));
  }
  fragments.push(...tools);
  return { sessionId, sidechain, timestamp, fragments };
}

/**
 * One user record is one request, however many text blocks it holds. Text the
 * CLI injected around it (reminders, notices) is kept apart as context, and a
 * slash command's expansion becomes the command the user typed (`/work 16097`).
 */
function userFragments(texts: readonly string[], meta: boolean): RecordFragment[] {
  if (texts.length === 0) return [];
  if (meta) return [{ kind: "context", text: texts.join("\n\n") }];
  const typed: string[] = [];
  const injected: string[] = [];
  for (const text of texts) {
    const command = isCommandInvocation(text) ? slashCommandOf(text) : null;
    if (command) typed.push(command);
    else (isInjected(text) ? injected : typed).push(text);
  }
  const fragments: RecordFragment[] = [];
  if (typed.length > 0) fragments.push({ kind: "prompt", text: typed.join("\n\n") });
  if (injected.length > 0) fragments.push({ kind: "context", text: injected.join("\n\n") });
  return fragments;
}

function isCommandInvocation(text: string): boolean {
  const start = text.trimStart();
  return start.startsWith("<command-message>") || start.startsWith("<command-name>");
}

export function slashCommandOf(text: string): string | null {
  const name = /<command-name>([^<]{1,200})<\/command-name>/.exec(text)?.[1]?.trim();
  if (!name) return null;
  const args = /<command-args>([^<]{0,2000})<\/command-args>/.exec(text)?.[1]?.trim();
  return args ? `${name} ${args}` : name;
}

function isInjected(text: string): boolean {
  const start = text.trimStart();
  return INJECTED_PREFIXES.some((prefix) => start.startsWith(prefix));
}

function joinText(content: unknown, types: readonly string[]): string {
  if (typeof content === "string") return content.trim();
  if (!Array.isArray(content)) return "";
  const parts: string[] = [];
  for (const raw of content) {
    const block = asObject(raw);
    if (block && types.includes(String(block.type)) && typeof block.text === "string") {
      parts.push(block.text);
    }
  }
  return parts.join("\n").trim();
}

function toolOutputText(output: unknown): string {
  if (typeof output === "string") {
    // A function call's output is often itself JSON carrying the text.
    const inner = tryParseObject(output);
    if (inner && typeof inner.output === "string") return inner.output.trim();
    return output.trim();
  }
  if (Array.isArray(output)) return joinText(output, ["input_text", "output_text", "text"]);
  const object = asObject(output);
  if (object) {
    if (typeof object.output === "string") return object.output.trim();
    if (object.content !== undefined) return toolOutputText(object.content);
  }
  return "";
}

function capTool(text: string): string {
  const trimmed = text.trim();
  return trimmed.length > TOOL_TEXT_MAX_CHARS
    ? `${trimmed.slice(0, TOOL_TEXT_MAX_CHARS)}\n[… truncated for the index]`
    : trimmed;
}

function safeJson(value: unknown): string {
  try {
    return JSON.stringify(value) ?? "";
  } catch {
    return "";
  }
}

function tryParseObject(text: string): Record<string, unknown> | null {
  const start = text.trimStart();
  if (!start.startsWith("{")) return null;
  try {
    return asObject(JSON.parse(start));
  } catch {
    return null;
  }
}

function asObject(value: unknown): Record<string, unknown> | null {
  return value && typeof value === "object" && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : null;
}

function stringOrNull(value: unknown): string | null {
  return typeof value === "string" && value.length > 0 ? value : null;
}
