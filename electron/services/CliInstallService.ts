// eager-import-allow: performs sync fs checks while detecting and installing the agent CLI
import fs from "fs";
import path from "path";
import os from "os";
import { app } from "electron";
import type { CliInstallStatus } from "../../shared/types/ipc/system.js";
import { isAppImageUpdateRename } from "../utils/appImageRename.js";
import { resilientAtomicWriteFileSync, resilientRenameSync } from "../utils/fs.js";

const CLI_COMMAND_NAME = "daintree";
const CLI_SCRIPT_FILE = "daintree-cli.sh";
const INSTALL_TARGETS_MACOS = [
  `/usr/local/bin/${CLI_COMMAND_NAME}`,
  `${os.homedir()}/.local/bin/${CLI_COMMAND_NAME}`,
];
const INSTALL_TARGETS_LINUX = [
  `/usr/local/bin/${CLI_COMMAND_NAME}`,
  `${os.homedir()}/.local/bin/${CLI_COMMAND_NAME}`,
];
const SYMLINK_FALLBACK_ERROR_CODES = new Set(["EINVAL", "ENOSYS", "EOPNOTSUPP", "EPERM"]);

function isAppImage(): boolean {
  return (
    process.platform === "linux" &&
    typeof process.env.APPIMAGE === "string" &&
    process.env.APPIMAGE.length > 0
  );
}

function getAppImageWrapperDir(): string {
  const xdgDataHome = process.env.XDG_DATA_HOME || path.join(os.homedir(), ".local", "share");
  return path.join(xdgDataHome, CLI_COMMAND_NAME);
}

function getAppImageWrapperPath(): string {
  return path.join(getAppImageWrapperDir(), CLI_SCRIPT_FILE);
}

const APPIMAGE_WRAPPER_HEADER = "# Auto-generated by Daintree — do not edit";
const APPIMAGE_WRAPPER_LAUNCH_SUFFIX = ' --cli-path="$ABSOLUTE_PATH" &';
// What wrappers written before #11410 end their launch line with.
const APPIMAGE_WRAPPER_LAUNCH_SUFFIXES = [
  APPIMAGE_WRAPPER_LAUNCH_SUFFIX,
  ' --cli-path "$ABSOLUTE_PATH" &',
];

function appVersion(): string {
  try {
    return app.getVersion();
  } catch {
    return "unknown";
  }
}

/**
 * The `daintree` command for an AppImage install. It answers the same flags as
 * the packaged CLI script (resources/daintree-cli.sh); the version is written
 * in because the image's app.asar can't be read without mounting it, and the
 * wrapper is rewritten whenever its content no longer matches.
 */
export function generateAppImageWrapper(appImagePath: string, version = appVersion()): string {
  const escaped = appImagePath.replace(/'/g, "'\\''");
  const quotedVersion = version.replace(/[^0-9A-Za-z.+-]/g, "");
  return [
    "#!/usr/bin/env bash",
    APPIMAGE_WRAPPER_HEADER,
    "set -euo pipefail",
    'case "${1:-}" in',
    "  --help|-h)",
    `    printf '%s\\n' "Usage: ${CLI_COMMAND_NAME} [directory]" "" "Open a directory as a project in Daintree." "" "Arguments:" "  directory    Path to open (defaults to current directory)" "" "Options:" "  -h, --help       Show this help message" "  -v, --version    Show the Daintree CLI version" "  -s, --status     Check if Daintree is running"`,
    "    exit 0 ;;",
    "  --version|-v)",
    `    echo "${CLI_COMMAND_NAME} ${quotedVersion}"`,
    "    exit 0 ;;",
    "  --status|-s)",
    // This script's own command line matches the pattern too.
    '    if pgrep -f "(/|^)daintree([[:space:]]|$)" | grep -qvx "$$"; then echo "Daintree is running"; exit 0; fi',
    '    echo "Daintree is not running"; exit 1 ;;',
    "esac",
    'TARGET="${1:-.}"',
    `ABSOLUTE_PATH="$(cd -- "$TARGET" 2>/dev/null && pwd -P)" || { echo "${CLI_COMMAND_NAME}: '$TARGET' is not a directory" >&2; exit 1; }`,
    // Single-token `=` form: Chromium's `second-instance` command-line
    // reconstruction can inject a switch between a bare flag and its value
    // (#11410).
    `'${escaped}'${APPIMAGE_WRAPPER_LAUNCH_SUFFIX}`,
    "exit 0",
    "",
  ].join("\n");
}

/** The AppImage a wrapper written by {@link generateAppImageWrapper} launches; null for any other file. */
export function appImageOfWrapper(content: string): string | null {
  const lines = content.split("\n");
  if (lines[1] !== APPIMAGE_WRAPPER_HEADER) return null;
  for (const line of lines) {
    const suffix = APPIMAGE_WRAPPER_LAUNCH_SUFFIXES.find((candidate) => line.endsWith(candidate));
    if (!suffix) continue;
    const quoted = line.slice(0, -suffix.length);
    if (quoted.length < 2 || !quoted.startsWith("'") || !quoted.endsWith("'")) return null;
    return quoted.slice(1, -1).replace(/'\\''/g, "'");
  }
  return null;
}

/**
 * Point an installed AppImage wrapper at `appImage`, and any install that had
 * to copy the wrapper rather than link it. electron-updater renames a
 * versioned AppImage on update (Daintree-1.2.0.AppImage becomes
 * Daintree-1.3.0.AppImage) and deletes the old file, which would leave
 * `daintree` launching nothing. Only a wrapper whose image is gone and was
 * renamed into `appImage` moves; one naming any other AppImage is that
 * install's. A wrapper for this image written by an older template is brought
 * up to date. Nothing is created when the CLI was never installed.
 */
export function repointAppImageWrapper(appImage: string): boolean {
  const wrapperPath = getAppImageWrapperPath();
  const current = readFileIfExists(wrapperPath);
  if (current === null) return false;
  const named = appImageOfWrapper(current);
  if (named === null) return false;
  const next = generateAppImageWrapper(appImage);
  if (named === appImage && current === next) return false;
  if (named !== appImage && (!isAppImageUpdateRename(named, appImage) || fs.existsSync(named))) {
    return false;
  }

  resilientAtomicWriteFileSync(wrapperPath, next, "utf-8", { mode: 0o755 });
  for (const target of getInstallTargets()) {
    try {
      if (!fs.lstatSync(target).isSymbolicLink() && readFileIfExists(target) === current) {
        resilientAtomicWriteFileSync(target, next, "utf-8", { mode: 0o755 });
      }
    } catch {
      // Not installed there, or not writable: nothing of ours to refresh.
    }
  }
  console.log(`[CliInstallService] Pointed the daintree command at ${appImage}`);
  return true;
}

function ensureAppImageWrapper(): string {
  const wrapperDir = getAppImageWrapperDir();
  const wrapperPath = getAppImageWrapperPath();
  const content = generateAppImageWrapper(process.env.APPIMAGE!);

  fs.mkdirSync(wrapperDir, { recursive: true });
  resilientAtomicWriteFileSync(wrapperPath, content, "utf-8", { mode: 0o755 });

  return wrapperPath;
}

function getInstallTargets(): string[] {
  if (process.platform === "darwin") return INSTALL_TARGETS_MACOS;
  if (process.platform === "linux") return INSTALL_TARGETS_LINUX;
  return [];
}

function getScriptSourcePath(): string {
  if (isAppImage()) {
    return getAppImageWrapperPath();
  }
  if (app.isPackaged) {
    return path.join(process.resourcesPath, CLI_SCRIPT_FILE);
  }
  // Dev: app path points at project root when running `electron .`
  return path.join(app.getAppPath(), "scripts", CLI_SCRIPT_FILE);
}

function readFileIfExists(filePath: string): string | null {
  try {
    return fs.readFileSync(filePath, "utf8");
  } catch {
    return null;
  }
}

function getRealPath(filePath: string): string | null {
  try {
    return fs.realpathSync(filePath);
  } catch {
    return null;
  }
}

function asNodeError(err: unknown): NodeJS.ErrnoException {
  return err instanceof Error ? (err as NodeJS.ErrnoException) : new Error(String(err));
}

function canFallbackToCopy(err: unknown): boolean {
  const code = asNodeError(err).code;
  return typeof code === "string" && SYMLINK_FALLBACK_ERROR_CODES.has(code);
}

function isInstallUpToDate(targetPath: string, sourcePath: string): boolean {
  const sourceRealPath = getRealPath(sourcePath);
  if (!sourceRealPath) {
    return false;
  }

  try {
    const targetStats = fs.lstatSync(targetPath);
    if (targetStats.isSymbolicLink()) {
      return getRealPath(targetPath) === sourceRealPath;
    }
  } catch {
    return false;
  }

  const sourceContent = readFileIfExists(sourcePath);
  const targetContent = readFileIfExists(targetPath);
  return sourceContent !== null && targetContent !== null && sourceContent === targetContent;
}

function installAtTarget(targetPath: string, sourcePath: string): void {
  const dir = path.dirname(targetPath);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }

  if (fs.existsSync(targetPath)) {
    if (isInstallUpToDate(targetPath, sourcePath)) {
      return;
    }
  }

  const tempPath = `${targetPath}.${Date.now()}-${Math.random().toString(36).slice(2, 8)}.tmp`;

  try {
    fs.symlinkSync(sourcePath, tempPath);
  } catch (symErr) {
    if (!canFallbackToCopy(symErr)) {
      throw symErr;
    }
    const sourceContent = fs.readFileSync(sourcePath, "utf8");
    fs.writeFileSync(tempPath, sourceContent, { mode: 0o755 });
    fs.chmodSync(tempPath, 0o755);
  }

  try {
    resilientRenameSync(tempPath, targetPath);
  } catch {
    // Rename failed (rare: some Windows filesystems). Fall back to unlink +
    // direct create, then clean up the temp entry.
    try {
      fs.unlinkSync(tempPath);
    } catch {
      /* cleanup is best-effort */
    }
    if (fs.existsSync(targetPath)) {
      fs.unlinkSync(targetPath);
    }
    try {
      fs.symlinkSync(sourcePath, targetPath);
    } catch (err) {
      if (!canFallbackToCopy(err)) {
        throw err;
      }
      const sourceContent = fs.readFileSync(sourcePath, "utf8");
      fs.writeFileSync(targetPath, sourceContent, { mode: 0o755 });
      fs.chmodSync(targetPath, 0o755);
    }
  }
}

export async function install(): Promise<CliInstallStatus> {
  if (isAppImage()) {
    ensureAppImageWrapper();
  }

  const sourcePath = getScriptSourcePath();

  if (!fs.existsSync(sourcePath)) {
    throw new Error(`CLI script source not found: ${sourcePath}`);
  }

  const targets = getInstallTargets();
  if (targets.length === 0) {
    throw new Error("CLI installation is not supported on this platform.");
  }

  let lastError: Error | null = null;

  for (const target of targets) {
    try {
      installAtTarget(target, sourcePath);
      console.log(`[CliInstallService] Installed to ${target}`);
      return { installed: true, upToDate: true, path: target };
    } catch (err) {
      lastError = asNodeError(err);
      console.warn(`[CliInstallService] Could not write to ${target}:`, lastError.message);
    }
  }

  throw lastError ?? new Error("Failed to install CLI: no writable target found.");
}

export function getStatus(): CliInstallStatus {
  const sourcePath = getScriptSourcePath();
  const targets = getInstallTargets();

  for (const target of targets) {
    if (fs.existsSync(target)) {
      return {
        installed: true,
        upToDate: isInstallUpToDate(target, sourcePath),
        path: target,
      };
    }
  }

  return { installed: false, upToDate: false, path: targets[0] ?? "" };
}
