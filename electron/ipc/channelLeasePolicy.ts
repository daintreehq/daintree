export function getChannelLeasePolicy(channel: string): LeasePolicy {
  if (!Object.hasOwn(CHANNEL_LEASE_POLICY, channel)) return "free";
  return (CHANNEL_LEASE_POLICY as Record<string, LeasePolicy>)[channel]!;
}

/**
 * Whether a call on `channel` needs the caller to drive its project. A local
 * view is only held to it on `host` channels; see {@link CHANNEL_LEASE_POLICY}.
 */
export function requiresDriveLease(channel: string, caller: "link" | "local"): boolean {
  if (getChannelLeasePolicy(channel) !== "driver") return false;
  return caller === "link" || getChannelLocality(channel) === "host";
}
