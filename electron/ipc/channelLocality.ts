/**
 * Dynamic plugin push channels (`plugin:{id}:{channel}`) are owned by plugin
 * main code, which always runs on the Host.
 */
const DYNAMIC_PLUGIN_CHANNEL = /^plugin:[^:]+:.+$/;

export function getChannelLocality(channel: string): ChannelLocality | null {
  if (Object.hasOwn(CHANNEL_LOCALITY, channel)) {
    return (CHANNEL_LOCALITY as Record<string, ChannelLocality>)[channel]!;
  }
  if (Object.hasOwn(EVENT_LOCALITY, channel)) return EVENT_LOCALITY[channel]!;
  for (const rule of NAMESPACE_LOCALITY) {
    if (channel.startsWith(rule.prefix)) return rule.locality;
  }
  if (DYNAMIC_PLUGIN_CHANNEL.test(channel)) return "host";
  return null;
}
