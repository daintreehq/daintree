import type { ChannelName } from "./channels.js";

/**
 * Which machine answers each IPC channel when a window is attached to a
 * remote host.
 *
 * - `host`: the work itself (projects, terminals, git, files, agents, plugins,
 *   forge, MCP, persistence). Runs where the project lives.
 * - `shell`: the machine you're sitting at (windows, menus, theme, keybindings,
 *   sound, native notifications, updates, telemetry, voice, browser surfaces).
 * - `hybrid`: carries both, and needs an explicit split before it can cross a
 *   link (hydrate, events:push, project activation, native pickers, clipboard
 *   capture, notifications, keep-awake, settings bundles).
 *
 * The `mcp:` request/response bridge is `shell` although MCP is host work: it
 * joins a machine's main process to its own views. A host reaches a remote
 * view's renderer through the link's reverse requests, which the view's Shell
 * answers over this bridge.
 * The plugin prompt, capability-consent, action-dispatch and action-catalog
 * bridges are `shell` for the same reason: a host's plugin asks the driving
 * Shell by reverse request, and that Shell puts the question to its own view.
 * So is the worktree port receipt: it confirms a port this machine posted to
 * its own view (a remote view's is a relay this Shell holds).
 *
 * There is no default. The record is total over {@link ChannelName}, so a new
 * channel that isn't classified here fails typecheck, and
 * `npm run check:channel-locality` fails for channel strings registered
 * outside `CHANNELS`. Locally (no remote host) every channel keeps running in
 * this process exactly as before; the classification only drives routing for
 * remote-bound windows.
 */
