#!/usr/bin/env node
// API-surface snapshot guard for `@daintreehq/plugin-sdk`.
//
// The package is the public type surface third-party plugins compile against,
// exposed through two entry points — `.` (`dist/index.d.ts`) and `./react`
// (`dist/react.d.ts`). Nothing else in CI notices when a code change alters
// that exported shape: only runtime contract tests are gated. This guard
// snapshots the built declarations into git-tracked report files so any change
// to the surface forces a reviewed, committed update.
//
// The snapshot is taken from tsup's actual shipped `dist/*.d.ts` — the exact
// bytes consumers resolve — rather than a parallel declaration pipeline, so it
// reuses the hand-tuned `packages/plugin-sdk/tsup.config.ts` (the one that
// keeps `zod` external to avoid mangling `z.ZodType`). Because `dist/` is
// gitignored, the reports live under `packages/plugin-sdk/api-report/`.
//
// The package must be built before this script runs — the npm scripts
// (`check:api-surface`, `api-surface:update`) prepend the tsup build. Run
// without flags to regenerate the snapshots after an intentional API change;
// run with `--check` (CI) to fail on drift.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../..");

const UPDATE_COMMAND = "npm run api-surface:update";

// Each public entry point maps its built declaration to a committed snapshot.
const ENTRIES = [
  {
    name: ".",
    dist: path.join(root, "packages/plugin-sdk/dist/index.d.ts"),
    snapshot: path.join(root, "packages/plugin-sdk/api-report/index.d.ts"),
  },
  {
    name: "./react",
    dist: path.join(root, "packages/plugin-sdk/dist/react.d.ts"),
    snapshot: path.join(root, "packages/plugin-sdk/api-report/react.d.ts"),
  },
  {
    name: "./files",
    dist: path.join(root, "packages/plugin-sdk/dist/files.d.ts"),
    snapshot: path.join(root, "packages/plugin-sdk/api-report/files.d.ts"),
  },
];

const HEADER = [
  "// API surface snapshot for @daintreehq/plugin-sdk.",
  "// AUTO-GENERATED by scripts/ci/check-api-surface.mjs; do not edit by hand.",
  `// Run \`${UPDATE_COMMAND}\` after an intentional public API change and commit the result.`,
  "",
  "",
].join("\n");

// Collapse CRLF/CR to LF so a snapshot generated on Windows matches one from
// Linux/macOS — line endings are not part of the API surface.
export function normalizeLineEndings(text) {
  return text.replace(/\r\n?/g, "\n");
}

// Exactly one trailing newline, regardless of how the source ended.
export function ensureSingleTrailingNewline(text) {
  return `${text.replace(/\n+$/, "")}\n`;
}

// The committed snapshot = header + normalized declaration body.
export function renderSnapshot(declarationText) {
  return HEADER + ensureSingleTrailingNewline(normalizeLineEndings(declarationText));
}

// Bounded, readable diff between two snapshot strings. These are generated
// files, so a first-divergence window plus counts is enough to signal what
// changed and point the reader at the update command — we don't need a full
// LCS diff of a 3000-line file in the log.
export function compactDiff(expected, actual, { context = 3, window = 40 } = {}) {
  const expLines = expected.split("\n");
  const actLines = actual.split("\n");
  const max = Math.max(expLines.length, actLines.length);

  let firstDiff = -1;
  for (let i = 0; i < max; i++) {
    if (expLines[i] !== actLines[i]) {
      firstDiff = i;
      break;
    }
  }
  if (firstDiff === -1) return "";

  let added = 0;
  let removed = 0;
  for (let i = 0; i < max; i++) {
    if (expLines[i] !== actLines[i]) {
      if (actLines[i] !== undefined && !expLines.includes(actLines[i])) added++;
      if (expLines[i] !== undefined && !actLines.includes(expLines[i])) removed++;
    }
  }

  const start = Math.max(0, firstDiff - context);
  const lines = [];
  lines.push(`first divergence at line ${firstDiff + 1} (~${added} added, ~${removed} removed):`);
  for (let i = start; i < Math.min(max, start + window); i++) {
    const e = expLines[i];
    const a = actLines[i];
    if (e === a) {
      if (e !== undefined) lines.push(`  ${e}`);
    } else {
      if (e !== undefined) lines.push(`- ${e}`);
      if (a !== undefined) lines.push(`+ ${a}`);
    }
  }
  if (max > start + window) lines.push(`  … (${max - (start + window)} more lines)`);
  return lines.join("\n");
}

function readIfExists(file) {
  return existsSync(file) ? readFileSync(file, "utf8") : null;
}

// Compare one entry's built declaration against its committed snapshot.
// Returns { name, status: "ok" | "missing-dist" | "missing" | "stale", diff }.
export function compareEntry(entry) {
  const distText = readIfExists(entry.dist);
  if (distText === null) {
    return { name: entry.name, status: "missing-dist", diff: "" };
  }
  const expected = renderSnapshot(distText);
  const committed = readIfExists(entry.snapshot);
  if (committed === null) {
    return { name: entry.name, status: "missing", diff: "" };
  }
  const normalizedCommitted = normalizeLineEndings(committed);
  if (normalizedCommitted !== expected) {
    return { name: entry.name, status: "stale", diff: compactDiff(normalizedCommitted, expected) };
  }
  return { name: entry.name, status: "ok", diff: "" };
}

// Write one entry's snapshot from its built declaration. Returns true if the
// file changed on disk (or was newly created).
export function writeEntry(entry, { logger = console } = {}) {
  const distText = readIfExists(entry.dist);
  if (distText === null) {
    throw new Error(
      `Missing built declaration ${path.relative(root, entry.dist)} — build the package first (\`npm run build --workspace=packages/plugin-sdk\`).`
    );
  }
  const rendered = renderSnapshot(distText);
  const existing = readIfExists(entry.snapshot);
  mkdirSync(path.dirname(entry.snapshot), { recursive: true });
  const changed = existing === null || normalizeLineEndings(existing) !== rendered;
  if (changed) {
    writeFileSync(entry.snapshot, rendered);
    logger.log(
      `[check-api-surface] ${existing === null ? "created" : "updated"} ${path.relative(root, entry.snapshot)}`
    );
  } else {
    logger.log(`[check-api-surface] unchanged ${path.relative(root, entry.snapshot)}`);
  }
  return changed;
}

// --check mode: verify every entry matches its snapshot. Returns exit code.
export function runCheck(entries = ENTRIES, { logger = console } = {}) {
  let failures = 0;
  for (const entry of entries) {
    const result = compareEntry(entry);
    const rel = path.relative(root, entry.snapshot);
    if (result.status === "missing-dist") {
      logger.error(
        `::error file=${path.relative(root, entry.dist)}::Built declaration for \`${entry.name}\` is missing. ` +
          `The guard builds the package first; if you ran the script directly, build with \`npm run build --workspace=packages/plugin-sdk\`.`
      );
      failures++;
    } else if (result.status === "missing") {
      logger.error(
        `::error file=${rel}::Missing API surface snapshot for \`${entry.name}\`. ` +
          `Run \`${UPDATE_COMMAND}\` and commit the result.`
      );
      failures++;
    } else if (result.status === "stale") {
      logger.error(
        `::error file=${rel}::API surface snapshot for \`${entry.name}\` is out of sync with the built declarations. ` +
          `If this change to the public API is intentional, run \`${UPDATE_COMMAND}\` and commit the result.\n${result.diff}`
      );
      failures++;
    }
  }
  if (failures > 0) {
    logger.error(`\n[check-api-surface] API surface drift detected: ${failures} issue(s).`);
    return 1;
  }
  logger.log(
    "[check-api-surface] OK — @daintreehq/plugin-sdk API snapshots match built declarations"
  );
  return 0;
}

// Default mode: (re)generate every snapshot from the built declarations.
export function runUpdate(entries = ENTRIES, { logger = console } = {}) {
  let changed = 0;
  for (const entry of entries) {
    if (writeEntry(entry, { logger })) changed++;
  }
  logger.log(
    `[check-api-surface] ${changed === 0 ? "snapshots already up to date" : `${changed} snapshot(s) written`}`
  );
  return 0;
}

export function main(argv = process.argv.slice(2), { logger = console } = {}) {
  const unknown = argv.filter((a) => a !== "--check");
  if (unknown.length > 0) {
    logger.error(`[check-api-surface] unknown argument(s): ${unknown.join(", ")}`);
    logger.error("Usage: node scripts/ci/check-api-surface.mjs [--check]");
    return 2;
  }
  return argv.includes("--check") ? runCheck(ENTRIES, { logger }) : runUpdate(ENTRIES, { logger });
}

const isMain =
  import.meta.url === pathToFileURL(process.argv[1] ?? "").href ||
  (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]));

if (isMain) {
  process.exit(main());
}
